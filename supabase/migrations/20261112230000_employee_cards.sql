-- เมนูทำบัตรพนักงาน: บัตรประจำตัวผู้รับจ้างการไฟฟ้าส่วนภูมิภาค ปฏิบัติงานเกี่ยวกับมิเตอร์
-- (รูปแบบตาม TOR ข้อ 4.1 (7): บัตรสีขาว 9 x 6 ซม. ตัวหนังสือสีดำ, เลขที่ XXX/ปี, อายุ 1 ปี สิ้นสุด 31 ธ.ค.)
-- เข้าถึงผ่าน edge function employee-card-api เท่านั้น (admin)

create table if not exists public.employee_cards (
  id bigint generated by default as identity primary key,
  person_key text not null,               -- 'p:<employee_payroll_profiles.id>' หรือ 's:<ชื่อสตาฟ>' หรือ 'm:<ชื่อที่เพิ่มเอง>'
  payroll_profile_id bigint references public.employee_payroll_profiles(id) on delete set null,
  card_year int not null,                 -- ปี พ.ศ. ของเลขที่บัตร (XXX/ปี)
  card_no int not null,
  full_name text not null,
  contractor text not null default 'บริษัท ไดเวอร์เจนท์ คอร์ปอเรชั่น จำกัด',
  pea_office text,                        -- ประจำ กฟฟ.
  issue_date date not null default (now() at time zone 'Asia/Bangkok')::date,
  expire_date date,
  photo_b64 text,                         -- รูปถ่าย JPEG (ย่อแล้ว ~300x400) เก็บเป็น base64
  has_photo boolean generated always as (photo_b64 is not null) stored,
  is_active boolean not null default true,
  created_by bigint,
  updated_by bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (card_year, card_no)
);
create index if not exists employee_cards_person_idx on public.employee_cards (person_key, card_year);
alter table public.employee_cards enable row level security;
comment on table public.employee_cards is 'เมนูทำบัตรพนักงาน: บัตรประจำตัวผู้ปฏิบัติงานเกี่ยวกับมิเตอร์ (เข้าถึงผ่าน edge function employee-card-api เท่านั้น)';

-- ข้อมูลของแต่ละ กฟฟ. ที่พิมพ์บนบัตร: ผู้ลงนาม (ผจก.กฟฟ.คู่สัญญา) และเบอร์โทร
create table if not exists public.employee_card_offices (
  office text primary key,
  signer_name text,
  phone text,
  updated_by bigint,
  updated_at timestamptz not null default now()
);
alter table public.employee_card_offices enable row level security;
comment on table public.employee_card_offices is 'เมนูทำบัตรพนักงาน: ผู้ลงนามและเบอร์โทรของ กฟฟ. คู่สัญญา (เข้าถึงผ่าน employee-card-api เท่านั้น)';
