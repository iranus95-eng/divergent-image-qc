-- เมนูค้ำประกันสัญญา: สัญญาจ้างกับการไฟฟ้าส่วนภูมิภาคแต่ละ กฟฟ. พร้อมเงินค้ำประกัน (LG) และอากรแสตมป์ (ตราสาร)
-- ที่มา: ไฟล์ LG ปี 2570 (ชีต LG2570 = รายการที่ยังไม่ได้ LG, ชีต ตราสาร2570 = รายการที่ยังไม่ได้ตราสาร)
-- เข้าถึงผ่าน edge function contract-guarantee-api เท่านั้น (admin)

create table if not exists public.contract_guarantees (
  id bigint generated by default as identity primary key,
  contract_year int not null,                -- ปีสัญญา พ.ศ. (เช่น 2570)
  seq int,                                   -- ลำดับในตาราง
  pea_office text not null,                  -- ชื่อการไฟฟ้า
  tax_id text,                               -- เลขผู้เสียภาษี
  branch_no text,                            -- สาขาที่
  address text,
  contract_no text,                          -- เลขที่สัญญา
  contract_date date,                        -- ลว.
  wage_ex_vat numeric(14,2),                 -- ค่าจ้าง (ไม่รวม VAT)
  guarantee_amount numeric(14,2),            -- เงินค้ำประกัน
  period_start date,                         -- ระยะเวลา เริ่ม
  period_end date,                           -- ระยะเวลา สิ้นสุด
  lg_done boolean not null default false,    -- ทำ LG แล้ว
  lg_no text,                                -- เลขที่หนังสือค้ำประกัน
  lg_bank text,                              -- ธนาคารผู้ออก LG
  lg_date date,                              -- วันที่ออก LG
  stamp_done boolean not null default false, -- ทำตราสาร (อากรแสตมป์) แล้ว
  stamp_date date,
  note text,
  is_active boolean not null default true,
  created_by bigint,
  updated_by bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists contract_guarantees_year_idx on public.contract_guarantees (contract_year, seq) where is_active;
alter table public.contract_guarantees enable row level security;
comment on table public.contract_guarantees is 'เมนูค้ำประกันสัญญา: สัญญา กฟฟ. เงินค้ำประกัน LG และตราสาร (เข้าถึงผ่าน edge function contract-guarantee-api เท่านั้น)';
