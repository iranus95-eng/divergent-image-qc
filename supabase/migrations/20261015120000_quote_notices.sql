create table if not exists public.quote_notices (
  id bigint generated by default as identity primary key,
  title text not null,
  file_name text,
  pdf_b64 text not null,
  state jsonb not null default '{}'::jsonb,
  total_amount numeric(16,2),
  created_by bigint,
  updated_by bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists quote_notices_updated_idx on public.quote_notices (updated_at desc);
alter table public.quote_notices enable row level security;
